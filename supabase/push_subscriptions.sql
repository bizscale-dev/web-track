-- Stores each browser's Web Push subscription (one row per
-- browser/device/profile a person has granted notification permission on).
-- Only ever read/written via server actions using the service role key
-- (savePushSubscription, the pushToEmails helper in app/actions.ts) — never
-- queried directly from the browser client, so no RLS policy is needed.
create table if not exists push_subscriptions (
  id bigint generated by default as identity primary key,
  user_email text not null,
  endpoint text not null unique,
  p256dh text not null,
  auth text not null,
  created_at timestamptz not null default now()
);

create index if not exists push_subscriptions_email_idx
on push_subscriptions (user_email);
